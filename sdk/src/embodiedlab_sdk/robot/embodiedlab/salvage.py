"""Wrap up an episode whose benchmark process died (native crash, kill, OOM) or stopped answering.

The normal stop path asks the live benchmark process to finalize (/v1/finalize): it closes the video writer,
writes the process record and copies both out. A dead process cannot answer, and the run directory stays behind in
the container that the Worker removes. This module is run by the lifecycle adapter (bootstrap.Worker.finalize) in
a separate interpreter and salvages what the dead process left on disk:

- process/: the last process-record checkpoint the benchmark server wrote while it ran (server.py writes one before
  physics-advancing commands, at most every CHECKPOINT_S of wall time), marked end_reason='sim_diverged' with the
  exit status and the checkpoint tick, plus the backend's private logs (finish_process_record, truth excluded);
- video/video_three-view.mp4: the three-view video up to the crash. OpenCV's mp4 writer puts the index (moov) at the
  end, so a killed writer leaves ftyp + an open mdat of MPEG-4 Part 2 frames without the decoder configuration. The
  configuration is regenerated by encoding one frame at the bench's video size with the same writer settings, the
  frames are decoded with it and re-encoded into a playable file.

usage: python -m embodiedlab_sdk.robot.embodiedlab.salvage --run RUN --capture DIR --status TEXT [--device-log LOG]
Prints one JSON object (the capture output) on stdout.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

END_REASON = 'sim_diverged'           # the simulation ended abnormally; termination_detail has the exit status
VIDEO_SIZES = ((1536, 512), (1920, 640))     # every bench writes three 512 or 640 px views, mp4v, 30 fps
VIDEO_FPS = 30
VOP = b'\x00\x00\x01\xb6'
VOS = b'\x00\x00\x01\xb0'


def mdat_payload(data: bytes) -> bytes | None:
    """The frame bytes of an MP4 written by a killed writer (mdat open to the end of the file), or None."""
    pos = 0
    while pos + 8 <= len(data):
        size, kind, header = int.from_bytes(data[pos:pos + 4], 'big'), data[pos + 4:pos + 8], 8
        if size == 1:
            size, header = int.from_bytes(data[pos + 8:pos + 16], 'big'), 16
        if kind == b'mdat':
            end = pos + size if size >= header else len(data)
            payload = data[pos + header:end]
            start = payload.find(VOP)
            return payload[start:] if start >= 0 else None
        if kind == b'moov' or size < 8:
            return None
        pos += size
    return None


def decoder_config(size) -> bytes:
    """MPEG-4 Part 2 VOS/VOL header of OpenCV's mp4v writer at this frame size and 30 fps."""
    import cv2
    import numpy as np
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, 'ref.mp4')
        writer = cv2.VideoWriter(path, cv2.VideoWriter_fourcc(*'mp4v'), VIDEO_FPS, size)
        writer.write(np.zeros((size[1], size[0], 3), np.uint8))
        writer.release()
        data = Path(path).read_bytes()
    index = data.rfind(VOS)
    if index < 1:
        raise RuntimeError('reference encoding has no decoder configuration')
    return data[index:index + (data[index - 1] & 0x7f)]


def _decode_errors(raw: Path) -> int:
    """Decoder error lines when the raw stream is read with its regenerated configuration (a wrong frame size
    fails on every frame; the right one at most on the last, truncated frame)."""
    code = ('import cv2,sys\nc=cv2.VideoCapture(sys.argv[1])\nn=0\n'
            'while n<90 and c.read()[0]:n+=1\nprint(n)')
    result = subprocess.run([sys.executable, '-c', code, str(raw)], capture_output=True, text=True, timeout=300)
    frames = int(result.stdout.strip() or 0)
    errors = sum(1 for line in result.stderr.splitlines() if 'Error at MB' in line or 'damaged' in line)
    return errors if frames else 10**9


def recover_video(source: Path, destination: Path) -> dict:
    """Re-encode the frames of a truncated mp4 into a playable mp4. Returns what was done."""
    import cv2
    data = source.read_bytes()
    payload = mdat_payload(data)
    if payload is None:
        return {'video_recovered': False, 'video_error': 'no open mdat with MPEG-4 frames'}
    with tempfile.TemporaryDirectory() as tmp:
        best = None
        for size in VIDEO_SIZES:
            raw = Path(tmp) / f'{size[0]}x{size[1]}.m4v'
            raw.write_bytes(decoder_config(size) + payload[:4_000_000])
            errors = _decode_errors(raw)
            if best is None or errors < best[0]:
                best = (errors, size)
        raw = Path(tmp) / 'stream.m4v'
        raw.write_bytes(decoder_config(best[1]) + payload)
        capture, writer, frames = cv2.VideoCapture(str(raw)), None, 0
        destination.parent.mkdir(parents=True, exist_ok=True)
        while True:
            ok, frame = capture.read()
            if not ok:
                break
            if writer is None:
                writer = cv2.VideoWriter(str(destination), cv2.VideoWriter_fourcc(*'mp4v'), VIDEO_FPS,
                                         (frame.shape[1], frame.shape[0]))
            writer.write(frame)
            frames += 1
        if writer is not None:
            writer.release()
    return {'video_recovered': frames > 0, 'frame_count': frames, 'video_size': list(best[1])}


def salvage(run: Path, capture: Path, status: str, device_log: Path | None = None) -> dict:
    run, capture = Path(run), Path(capture)
    output = {'supported': True, 'enabled': True, 'finalized': True, 'salvaged': True, 'end_reason': END_REASON,
              'frame_count': 0, 'artifacts': {}}
    checkpoint = run / 'process_checkpoint'
    process = capture / 'process'
    meta = {}
    if (checkpoint / 'episode.json').is_file():
        shutil.copytree(checkpoint, process, dirs_exist_ok=True)
        meta = json.loads((process / 'checkpoint.json').read_text()) if (process / 'checkpoint.json').is_file() else {}
        episode = json.loads((process / 'episode.json').read_text())
        tail = ''
        if device_log and Path(device_log).is_file():
            lines = Path(device_log).read_text(errors='replace').splitlines()
            tail = ' | '.join(line for line in lines[-400:] if any(
                t in line for t in ('Error', 'error', 'Traceback', 'Segmentation', 'Fatal', 'Killed', 'abort', 'PhysX')))[-2000:]
        episode.update(end_reason=END_REASON, salvaged=True, checkpoint_tick=episode.get('end_tick'),
                       checkpoint_wall_time=meta.get('wall_time'),
                       termination_detail=f'benchmark process ended without finalizing ({status}); the record is the '
                                          f'last checkpoint, at physics tick {episode.get("end_tick")}'
                                          + (f'; device log: {tail}' if tail else ''))
        (process / 'episode.json').write_text(json.dumps(episode, indent=2, default=repr))
        (process / 'manifest.json').unlink(missing_ok=True)
        try:
            from instance_episodes import finish_process_record
            finish_process_record(run / 'private', process)
        except Exception as exc:          # the record above stays; only the private logs are missing
            output['private_logs_error'] = f'{type(exc).__name__}: {exc}'
        output['artifacts']['process'] = 'process'
    else:
        output['process_error'] = 'no process-record checkpoint'
    videos = [Path(meta['video_path'])] if meta.get('video_path') else sorted(run.glob('*.mp4'))
    for video in videos:
        if video.is_file() and video.stat().st_size > 0:
            target = capture / 'video' / 'video_three-view.mp4'
            try:
                result = recover_video(video, target)
            except Exception as exc:
                result = {'video_recovered': False, 'video_error': f'{type(exc).__name__}: {exc}'}
            output.update(result)
            if result.get('video_recovered'):
                output['artifacts']['video'] = 'video/video_three-view.mp4'
            break
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--run', required=True)
    parser.add_argument('--capture', required=True)
    parser.add_argument('--status', required=True)
    parser.add_argument('--device-log')
    args = parser.parse_args(argv)
    print(json.dumps(salvage(Path(args.run), Path(args.capture), args.status,
                             Path(args.device_log) if args.device_log else None)))


if __name__ == '__main__':
    main()
